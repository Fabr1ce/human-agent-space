import { lstat, readFile } from 'node:fs/promises';
import path from 'node:path';
import matter from 'gray-matter';
import yaml from 'js-yaml';
import { listFiles } from '../core/files.js';
import { listRules, listSkills } from '../core/knowledge.js';
import type { WorkspaceRoots } from '../core/workspace.js';
import type { AdapterId, GeneratedFile } from './types.js';

type RuleEntry = Awaited<ReturnType<typeof listRules>>[number];

export async function projectKnowledge(
  roots: WorkspaceRoots,
  agent: AdapterId,
  projectRulePath: (rule: RuleEntry) => string,
): Promise<GeneratedFile[]> {
  await assertCanonicalDirectories(roots);
  const generated: GeneratedFile[] = [];

  for (const rule of await listRules(roots)) {
    const raw = await readFile(rule.path);
    const parsed = matter(raw.toString('utf8'));
    const source = describeSource(rule.path, roots);
    const sourceComment = generatedComment(source);
    const body = [
      sourceComment,
      `# ${rule.description}`,
      '',
      parsed.content.trim(),
    ].filter(Boolean).join('\n');
    const frontmatter: Record<string, unknown> = {
      ...(agent === 'copilot'
        ? { applyTo: rule.globs.length ? rule.globs.join(', ') : '**' }
        : agent === 'kiro'
          ? rule.globs.length
            ? { inclusion: 'fileMatch', fileMatchPattern: rule.globs }
            : { inclusion: 'always' }
        : rule.globs.length
          ? { paths: rule.globs }
          : {}),
    };

    generated.push({
      agent,
      path: projectRulePath(rule),
      source,
      content: Buffer.from(renderMarkdown(body, frontmatter), 'utf8'),
    });
  }

  for (const skill of await listSkills(roots)) {
    const sourceDirectory = path.dirname(skill.path);
    if ((await lstat(sourceDirectory)).isSymbolicLink()) {
      throw new Error(`Refusing to project a skill directory that is a symbolic link: ${sourceDirectory}`);
    }
    const sourceFiles = await listFiles(sourceDirectory);
    const parsed = matter((await readFile(skill.path, 'utf8')));
    const sourcePrefix = skillRootFor(agent, skill.name);

    for (const sourcePath of sourceFiles) {
      const raw = await readFile(sourcePath);
      const relativePath = path.relative(sourceDirectory, sourcePath).split(path.sep).join('/');
      const source = describeSource(sourcePath, roots);
      let output = raw;

      if (relativePath === 'SKILL.md') {
        const canonical = parsed.data as Record<string, unknown>;
        const metadata: Record<string, string> = {
          'has-schema-version': String(canonical.schema_version),
          'has-version': String(canonical.version),
          'has-compatibility': (canonical.compatibility as string[]).join(', '),
          'has-tags': (canonical.tags as string[]).join(', '),
          'has-author': String(canonical.author),
        };
        const frontmatter: Record<string, unknown> = {
          name: skill.name,
          description: skill.description,
          metadata,
        };
        const body = [generatedComment(source), parsed.content.trim()].filter(Boolean).join('\n\n');
        output = Buffer.from(renderMarkdown(body, frontmatter), 'utf8');
      }

      generated.push({
        agent,
        path: path.posix.join(sourcePrefix, relativePath),
        source,
        content: output,
      });
    }
  }

  return generated.sort((left, right) => left.path.localeCompare(right.path));
}

function skillRootFor(agent: AdapterId, name: string): string {
  const root = {
    copilot: '.github',
    'claude-code': '.claude',
    kiro: '.kiro',
  }[agent];
  return path.posix.join(root, 'skills', name);
}

async function assertCanonicalDirectories(roots: WorkspaceRoots): Promise<void> {
  const workspaceRoots = [roots.globalRoot, roots.projectRoot].filter(
    (root): root is string => root !== null,
  );
  for (const root of workspaceRoots) {
    for (const directory of ['rules', 'skills']) {
      const sourcePath = path.join(root, directory);
      try {
        const info = await lstat(sourcePath);
        if (info.isSymbolicLink() || !info.isDirectory()) {
          throw new Error(`Refusing to read canonical knowledge through a non-directory or symbolic link: ${sourcePath}`);
        }
      } catch (error) {
        if (!isNotFound(error)) {
          throw error;
        }
      }
    }
  }
}

function renderMarkdown(body: string, frontmatter: Record<string, unknown>): string {
  const serialized = yaml.dump(frontmatter, { lineWidth: -1, noRefs: true }).trimEnd();
  return `---\n${serialized}\n---\n\n${body.trimEnd()}\n`;
}

function generatedComment(source: string): string {
  const safeSource = source
    .replaceAll(/[\u0000-\u001f\u007f]/g, (character) => encodeURIComponent(character))
    .replaceAll('--', '%2D%2D')
    .replaceAll('>', '%3E');
  return `<!-- Generated by HAS; source: ${safeSource} -->`;
}

function describeSource(filePath: string, roots: WorkspaceRoots): string {
  const root = findSourceRoot(filePath, roots);
  if (!root) {
    throw new Error(`Canonical source is outside the configured workspaces: ${filePath}`);
  }
  const relativePath = path.relative(root, filePath).split(path.sep).join('/');
  return root === roots.globalRoot ? `~/.has/${relativePath}` : `.has/${relativePath}`;
}

function findSourceRoot(filePath: string, roots: WorkspaceRoots): string | undefined {
  const candidates = [roots.projectRoot, roots.globalRoot].filter(
    (root): root is string => root !== null,
  );
  return candidates.find((root) => {
    const relative = path.relative(root, filePath);
    return relative !== '' && !relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative);
  });
}

function isNotFound(error: unknown): boolean {
  return error instanceof Error && 'code' in error && error.code === 'ENOENT';
}
