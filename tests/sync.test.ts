import { mkdir, mkdtemp, readFile, rm, unlink, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { getAdapter, listAdapters } from '../src/adapters/registry.js';
import type { WorkspaceRoots } from '../src/core/workspace.js';
import { adoptWorkspaceFile, syncWorkspace } from '../src/sync/engine.js';

const temporaryDirectories: string[] = [];

async function makeWorkspace(): Promise<WorkspaceRoots> {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'has-sync-test-'));
  temporaryDirectories.push(directory);
  const repositoryRoot = path.join(directory, 'repo');
  const projectRoot = path.join(repositoryRoot, '.has');
  const globalRoot = path.join(directory, 'home', '.has');
  await mkdir(path.join(projectRoot, 'rules'), { recursive: true });
  await mkdir(path.join(projectRoot, 'skills', 'formatter', 'resources'), { recursive: true });
  await mkdir(globalRoot, { recursive: true });
  await writeFile(
    path.join(projectRoot, 'rules', 'style.md'),
    `---\nschema_version: 1\nid: rule-style\ndescription: Use consistent style\nscope: project\npriority: 10\nglobs: [\"src/**/*.ts\", \"tests/**/*.ts\"]\nauthor: human\n---\nUse strict types.\n`,
  );
  await writeFile(
    path.join(projectRoot, 'skills', 'formatter', 'SKILL.md'),
    `---\nschema_version: 1\nname: formatter\ndescription: Format source files\nversion: 1.2.0\ncompatibility: [copilot, claude-code]\ntags: [formatting]\nauthor: human\n---\nFormat files consistently.\n`,
  );
  await writeFile(path.join(projectRoot, 'skills', 'formatter', 'resources', 'guide.txt'), 'Keep examples readable.\n');
  return {
    globalRoot,
    projectRoot,
    localRoot: path.join(projectRoot, '.local'),
    repositoryRoot,
  };
}

afterEach(async () => {
  await Promise.all(temporaryDirectories.splice(0).map((directory) => rm(directory, { recursive: true, force: true })));
});

describe('Copilot and Claude Code adapters', () => {
  it('projects rules and native skills to documented agent locations', async () => {
    const roots = await makeWorkspace();
    await mkdir(path.join(roots.globalRoot, 'rules'), { recursive: true });
    await writeFile(
      path.join(roots.globalRoot, 'rules', 'shared.md'),
      `---\nschema_version: 1\nid: rule-global\ndescription: Global guidance\nscope: global\npriority: 1\nglobs: []\nauthor: human\n---\nGlobal instruction.\n`,
    );
    const copilotFiles = await getAdapter('copilot').project(roots);
    const claudeFiles = await getAdapter('claude-code').project(roots);
    const copilotRule = copilotFiles.find((file) => file.path.endsWith('rule-style.instructions.md'));
    const claudeRule = claudeFiles.find((file) => file.path === '.claude/rules/rule-style.md');
    const copilotSkill = copilotFiles.find((file) => file.path === '.github/skills/formatter/SKILL.md');
    const claudeSkill = claudeFiles.find((file) => file.path === '.claude/skills/formatter/SKILL.md');

    expect(copilotRule?.path).toBe('.github/instructions/rule-style.instructions.md');
    expect(copilotRule?.content.toString()).toContain('applyTo: src/**/*.ts, tests/**/*.ts');
    expect(copilotRule?.content.toString()).toContain('Generated by HAS; source: .has/rules/style.md');
    expect(claudeRule?.content.toString()).toContain('paths:');
    expect(claudeRule?.content.toString()).toContain('src/**/*.ts');
    expect(copilotSkill?.content.toString()).toContain('name: formatter');
    expect(copilotSkill?.content.toString()).toContain('has-version: 1.2.0');
    expect(claudeSkill?.content.toString()).toContain('Format files consistently.');
    expect(copilotFiles.find((file) => file.path.includes('rule-global'))?.content.toString())
      .toContain('source: ~/.has/rules/shared.md');
    expect(copilotFiles.find((file) => file.path.endsWith('resources/guide.txt'))?.content.toString())
      .toBe('Keep examples readable.\n');
    expect(claudeFiles.map((file) => file.path)).toContain('.claude/skills/formatter/resources/guide.txt');
  });

  it.each(['copilot', 'claude-code'] as const)(
    '%s provides detection, capabilities, plan, apply, check, and adopt',
    async (agent) => {
      const roots = await makeWorkspace();
      const adapter = getAdapter(agent);
      expect((await adapter.detect(roots)).configured).toBe(false);
      expect(adapter.capabilities()).toMatchObject({
        pathScopedRules: true,
        nativeSkills: true,
        verified: agent === 'copilot' ? 'partial' : 'verified',
      });

      const plan = await adapter.plan(roots);
      expect(plan.operations.some((operation) => operation.action === 'create')).toBe(true);
      const applied = await adapter.apply(plan);
      expect(applied.blocked).toBe(false);
      expect((await adapter.detect(roots)).configured).toBe(true);
      expect((await adapter.check(roots)).drift).toBe(false);

      const generatedTarget = plan.operations.find((operation) => operation.path.endsWith('SKILL.md'))?.path;
      expect(generatedTarget).toBeDefined();
      const targetPath = path.join(roots.repositoryRoot!, generatedTarget!);
      await writeFile(targetPath, 'Edited generated skill.\n');
      expect((await adapter.check(roots)).blocked).toBe(true);

      const adopted = await adapter.adopt(roots, generatedTarget!);
      expect(adopted.backup).toBeDefined();
      expect(await readFile(path.join(roots.repositoryRoot!, adopted.backup!), 'utf8'))
        .toBe('Edited generated skill.\n');
      expect((await adapter.check(roots)).drift).toBe(false);
    },
  );
});

describe('sync planning and apply', () => {
  it('keeps dry-run read-only, applies idempotently, and detects canonical drift', async () => {
    const roots = await makeWorkspace();
    const dryRun = await syncWorkspace(roots, listAdapters(), { agent: 'copilot', dryRun: true });
    const ruleTarget = path.join(roots.repositoryRoot!, '.github/instructions/rule-style.instructions.md');
    expect(dryRun.operations.map((operation) => operation.action)).toContain('create');
    await expect(readFile(ruleTarget, 'utf8')).rejects.toMatchObject({ code: 'ENOENT' });
    await expect(readFile(path.join(roots.projectRoot!, '.local/sync-manifest.json'), 'utf8'))
      .rejects.toMatchObject({ code: 'ENOENT' });

    const first = await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    expect(first.applied.length).toBeGreaterThan(1);
    expect(await readFile(ruleTarget, 'utf8')).toContain('Use strict types.');

    const second = await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    expect(second.drift).toBe(false);
    expect(second.operations.every((operation) => operation.action === 'unchanged')).toBe(true);

    await writeFile(
      path.join(roots.projectRoot!, 'rules/style.md'),
      `---\nschema_version: 1\nid: rule-style\ndescription: Use consistent style\nscope: project\npriority: 10\nglobs: [\"src/**/*.ts\", \"tests/**/*.ts\"]\nauthor: human\n---\nUse strict typed APIs.\n`,
    );
    const check = await syncWorkspace(roots, listAdapters(), { agent: 'copilot', check: true });
    expect(check.drift).toBe(true);
    expect(check.operations.find((operation) => operation.path.endsWith('rule-style.instructions.md'))?.action)
      .toBe('update');
    expect(await readFile(ruleTarget, 'utf8')).toContain('Use strict types.');
  });

  it('blocks the whole apply when a target is hand-authored and explicitly backs it up on adopt', async () => {
    const roots = await makeWorkspace();
    const target = path.join(roots.repositoryRoot!, '.github/instructions/rule-style.instructions.md');
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, 'Human instructions that must not be overwritten.\n');

    const blocked = await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    expect(blocked.blocked).toBe(true);
    expect(blocked.applied).toEqual([]);
    await expect(readFile(target, 'utf8')).resolves.toContain('Human instructions');
    await expect(readFile(path.join(roots.repositoryRoot!, '.github/skills/formatter/SKILL.md'), 'utf8'))
      .rejects.toMatchObject({ code: 'ENOENT' });

    const preview = await adoptWorkspaceFile(roots, '.github/instructions/rule-style.instructions.md', listAdapters(), true);
    expect(preview.operations.find((operation) => operation.path.endsWith('rule-style.instructions.md'))?.reason)
      .toBe('would adopt after backup');
    await expect(readFile(target, 'utf8')).resolves.toContain('Human instructions');

    const adoption = await adoptWorkspaceFile(roots, '.github/instructions/rule-style.instructions.md', listAdapters());
    expect(adoption.backup).toBeDefined();
    expect(await readFile(path.join(roots.repositoryRoot!, adoption.backup!), 'utf8'))
      .toContain('Human instructions');
    await expect(readFile(target, 'utf8')).resolves.toContain('Use strict types.');
    await expect(readFile(path.join(roots.repositoryRoot!, '.github/skills/formatter/SKILL.md'), 'utf8'))
      .rejects.toMatchObject({ code: 'ENOENT' });

    const remaining = await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    expect(remaining.blocked).toBe(false);
    expect(remaining.applied.length).toBeGreaterThan(0);
  });

  it('does not silently claim an unowned target even when its bytes match generated output', async () => {
    const roots = await makeWorkspace();
    const target = path.join(roots.repositoryRoot!, '.github/instructions/rule-style.instructions.md');
    const generated = (await getAdapter('copilot').project(roots))
      .find((file) => file.path === '.github/instructions/rule-style.instructions.md');
    expect(generated).toBeDefined();
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, generated!.content);

    const result = await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    expect(result.blocked).toBe(true);
    expect(result.operations.find((operation) => operation.path.endsWith('rule-style.instructions.md'))?.action)
      .toBe('conflict');
    await expect(readFile(path.join(roots.projectRoot!, '.local/sync-manifest.json'), 'utf8'))
      .rejects.toMatchObject({ code: 'ENOENT' });
  });

  it('adopts only the requested conflict when other targets also conflict', async () => {
    const roots = await makeWorkspace();
    const ruleTarget = '.github/instructions/rule-style.instructions.md';
    const skillTarget = '.github/skills/formatter/SKILL.md';
    const generated = await getAdapter('copilot').project(roots);
    for (const target of [ruleTarget, skillTarget]) {
      const file = generated.find((candidate) => candidate.path === target);
      expect(file).toBeDefined();
      const absolutePath = path.join(roots.repositoryRoot!, target);
      await mkdir(path.dirname(absolutePath), { recursive: true });
      await writeFile(absolutePath, `Manual version of ${target}`);
    }

    expect((await syncWorkspace(roots, listAdapters(), { agent: 'copilot' })).blocked).toBe(true);
    const adopted = await adoptWorkspaceFile(roots, ruleTarget, listAdapters());

    expect(adopted.blocked).toBe(false);
    expect(adopted.operations).toHaveLength(1);
    expect(adopted.applied).toEqual([ruleTarget]);
    await expect(readFile(path.join(roots.repositoryRoot!, skillTarget), 'utf8'))
      .resolves.toBe(`Manual version of ${skillTarget}`);
  });

  it('preserves direct edits to generated files and offers explicit adoption', async () => {
    const roots = await makeWorkspace();
    await syncWorkspace(roots, listAdapters(), { agent: 'claude-code' });
    const target = path.join(roots.repositoryRoot!, '.claude/rules/rule-style.md');
    await writeFile(target, 'User edit to generated instructions.\n');

    const result = await syncWorkspace(roots, listAdapters(), { agent: 'claude-code' });
    expect(result.blocked).toBe(true);
    expect(result.operations.find((operation) => operation.path === '.claude/rules/rule-style.md')?.reason)
      .toContain('edited after HAS generated it');
    await expect(readFile(target, 'utf8')).resolves.toBe('User edit to generated instructions.\n');
  });

  it('plans stale generated-file removal and deletes only unmodified managed outputs', async () => {
    const roots = await makeWorkspace();
    await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    await unlink(path.join(roots.projectRoot!, 'rules/style.md'));

    const preview = await syncWorkspace(roots, listAdapters(), { agent: 'copilot', dryRun: true });
    expect(preview.operations.some((operation) => operation.action === 'delete')).toBe(true);
    expect(await readFile(path.join(roots.repositoryRoot!, '.github/instructions/rule-style.instructions.md'), 'utf8'))
      .toContain('Use strict types.');

    const applied = await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    expect(applied.applied).toContain('.github/instructions/rule-style.instructions.md');
    await expect(readFile(path.join(roots.repositoryRoot!, '.github/instructions/rule-style.instructions.md'), 'utf8'))
      .rejects.toMatchObject({ code: 'ENOENT' });
  });

  it('preserves a modified stale output and fails closed on a malformed manifest', async () => {
    const roots = await makeWorkspace();
    await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    const staleTarget = path.join(roots.repositoryRoot!, '.github/instructions/rule-style.instructions.md');
    await unlink(path.join(roots.projectRoot!, 'rules/style.md'));
    await writeFile(staleTarget, 'Keep this manual edit.\n');

    const stale = await syncWorkspace(roots, listAdapters(), { agent: 'copilot' });
    expect(stale.blocked).toBe(true);
    await expect(readFile(staleTarget, 'utf8')).resolves.toBe('Keep this manual edit.\n');

    await mkdir(path.join(roots.projectRoot!, '.local'), { recursive: true });
    await writeFile(path.join(roots.projectRoot!, '.local/sync-manifest.json'), '{not-json');
    await expect(syncWorkspace(roots, listAdapters(), { agent: 'copilot' })).rejects.toThrow('invalid JSON');
  });

  it('rejects symlinked output paths instead of writing outside the repository', async () => {
    const roots = await makeWorkspace();
    const outside = path.join(path.dirname(roots.repositoryRoot!), 'outside');
    await mkdir(outside, { recursive: true });
    try {
      await import('node:fs/promises').then(({ symlink }) =>
        symlink(outside, path.join(roots.repositoryRoot!, '.github')),
      );
    } catch (error) {
      if (error instanceof Error && 'code' in error && ['EPERM', 'ENOTSUP'].includes(String(error.code))) {
        return;
      }
      throw error;
    }

    await expect(syncWorkspace(roots, listAdapters(), { agent: 'copilot' })).rejects.toThrow('symbolic link');
    await expect(readFile(path.join(outside, 'instructions/rule-style.instructions.md'), 'utf8'))
      .rejects.toMatchObject({ code: 'ENOENT' });
  });
});
